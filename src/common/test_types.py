# ── LinkMetadata ────────────────────────────────────────────────────────────

class TestLinkMetadata:
    """Metadata for a web link to be scraped and indexed."""

    def test_all_fields(self):
        """title, author, date, and source are all required."""
        lm = LinkMetadata(
            title="AI in Marketing 2025",
            author="Jane Doe",
            date="2025-03-15",
            source="https://example.com/ai-marketing",
        )
        assert lm.title == "AI in Marketing 2025"
        assert lm.author == "Jane Doe"
        assert lm.source.startswith("https://")

    def test_model_dump(self):
        """Serializes for PineconeScrapeAndPush payloads."""
        lm = LinkMetadata(
            title="Test", author="A", date="2025-01-01", source="https://x.com"
        )
        d = lm.model_dump()
        assert d["title"] == "Test"
        assert d["source"] == "https://x.com"


# ── ScrapeAndPushArgs ───────────────────────────────────────────────────────

class TestScrapeAndPushArgs:
    """Arguments for the Pinecone scrape-and-push tool."""

    def test_single_url(self):
        """Maps one URL to its metadata."""
        args = ScrapeAndPushArgs(
            result_dict={
                "https://example.com": LinkMetadata(
                    title="Page", author="A", date="2025-01-01", source="example.com"
                )
            }
        )
        assert "https://example.com" in args.result_dict

    def test_multiple_urls(self):
        """Can batch multiple URLs in one call."""
        args = ScrapeAndPushArgs(
            result_dict={
                "https://a.com": LinkMetadata(
                    title="A", author="a", date="1", source="a.com"
                ),
                "https://b.com": LinkMetadata(
                    title="B", author="b", date="2", source="b.com"
                ),
            }
        )
        assert len(args.result_dict) == 2


